    /** Entropy sizes BIP-39 allows: 128 bits (12 words) and 256 bits (24 words). */
    private val ALLOWED_ENTROPY_LENGTHS = setOf(16, 32)

    /**
     * Entropy -> mnemonic. The entropy is 16 or 32 bytes; the checksum is the
     * first `ENT / 32` bits of SHA-256(entropy), appended to the entropy before
     * the bit stream is cut into 11-bit word indexes.
     */
    fun entropyToMnemonic(entropy: ByteArray): List<String> {
        require(entropy.size in ALLOWED_ENTROPY_LENGTHS) {
            "BIP-39 entropy is 16 or 32 bytes, got ${entropy.size}"
        }

        val checksumBits = entropy.size * 8 / 32
        val checksum = Hashes.sha256(entropy)

        val bits = StringBuilder(entropy.size * 8 + checksumBits)
        entropy.forEach { byte -> appendBits(bits, byte.toInt() and 0xFF, 8) }
        // The checksum is the *leading* checksumBits bits of the digest's first byte.
        appendBits(bits, (checksum[0].toInt() and 0xFF) ushr (8 - checksumBits), checksumBits)

        return (0 until bits.length / 11).map { wordlist[bitsToInt(bits, it * 11, 11)] }
    }

    /**
     * Mnemonic -> entropy, verifying the checksum.
     *
     * Throws [IllegalArgumentException] for an unknown word, a word count that
     * is not 12 or 24, or a checksum that does not match.
     */
    fun mnemonicToEntropy(words: List<String>): ByteArray {
        require(words.size == 12 || words.size == 24) {
            "a BIP-39 mnemonic is 12 or 24 words, got ${words.size}"
        }

        val bits = StringBuilder(words.size * 11)
        words.forEach { word ->
            val index = wordIndex(word)
                ?: throw IllegalArgumentException("'$word' is not in the BIP-39 English wordlist")
            appendBits(bits, index, 11)
        }

        val entropyBits = words.size * 32 / 3   // 12 words -> 128, 24 words -> 256
        val checksumBits = entropyBits / 32
        require(bits.length == entropyBits + checksumBits) { "the mnemonic does not decode to whole entropy" }

        val entropy = ByteArray(entropyBits / 8)
        for (i in entropy.indices) entropy[i] = bitsToInt(bits, i * 8, 8).toByte()

        val expectedChecksum = Hashes.sha256(entropy)
        val actualChecksum = bitsToInt(bits, entropyBits, checksumBits)
        val expected = (expectedChecksum[0].toInt() and 0xFF) ushr (8 - checksumBits)
        require(actualChecksum == expected) { "the mnemonic's checksum is wrong" }

        return entropy
    }

    /** Whether [words] is a well-formed, correctly checksummed 12- or 24-word mnemonic. */
    fun isValid(words: List<String>): Boolean = try {
        mnemonicToEntropy(words)
        true
    } catch (e: IllegalArgumentException) {
        false
    }

    /**
     * Mnemonic -> 64-byte seed: PBKDF2-HMAC-SHA512(mnemonic, "mnemonic" + passphrase,
     * 2048 rounds, 64 bytes).
     *
     * PBKDF2 is hand-rolled over [Hashes.hmacSha512] rather than delegating to a
     * `SecretKeyFactory`, because provider differences across devices would make
     * the same mnemonic produce different wallets. Both the mnemonic sentence and
     * the salt are NFKD-normalised first, as BIP-39 requires (and as SeedSigner
     * does) — for English that is a no-op, but a passphrase with an accented
     * character would otherwise derive a different seed than the signer expects.
     */
    fun mnemonicToSeed(words: List<String>, passphrase: String = ""): ByteArray {
        val mnemonic = normalize(words.joinToString(" "))
        val salt = normalize("mnemonic$passphrase")
        return pbkdf2HmacSha512(
            password = mnemonic.toByteArray(Charsets.UTF_8),
            salt = salt.toByteArray(Charsets.UTF_8),
            iterations = PBKDF2_ROUNDS,
            outputLength = HMAC_SHA512_LENGTH,
        )
    }

    /** NFKD, the Unicode normal form BIP-39 mandates for mnemonic and passphrase. */
    private fun normalize(text: String): String = Normalizer.normalize(text, Normalizer.Form.NFKD)

    /**
     * PBKDF2 (RFC 2898 §5.2) with HMAC-SHA512 as the PRF.
     *
     * `T_i = U_1 xor U_2 xor ... xor U_c`, where `U_1 = PRF(P, S || INT_32_BE(i))`
     * and `U_j = PRF(P, U_{j-1})`. The derived key is the concatenation of the
     * `T_i`, truncated to [outputLength].
     */
    private fun pbkdf2HmacSha512(
        password: ByteArray,
        salt: ByteArray,
        iterations: Int,
        outputLength: Int,
    ): ByteArray {
        val blocks = (outputLength + HMAC_SHA512_LENGTH - 1) / HMAC_SHA512_LENGTH
        val derived = ByteArray(blocks * HMAC_SHA512_LENGTH)
        val block = ByteArray(HMAC_SHA512_LENGTH)

        for (b in 1..blocks) {
            // U_1 = PRF(P, S || INT_32_BE(b))
            var u = Hashes.hmacSha512(password, salt + byteArrayOf(
                (b ushr 24).toByte(),
                (b ushr 16).toByte(),
                (b ushr 8).toByte(),
                b.toByte(),
            ))
            u.copyInto(block)
            for (round in 2..iterations) {
                u = Hashes.hmacSha512(password, u)
                for (i in block.indices) block[i] = (block[i].toInt() xor u[i].toInt()).toByte()
            }
            block.copyInto(derived, (b - 1) * HMAC_SHA512_LENGTH)
        }

        return derived.copyOf(outputLength)
    }

    /** The index of [word], or null if it is not in the list. Binary search, as the list is sorted. */
    private fun wordIndex(word: String): Int? {
        val found = wordlist.binarySearch(word)
        return if (found >= 0) found else null
    }

    /** Appends the low [count] bits of [value], most significant first. */
    private fun appendBits(target: StringBuilder, value: Int, count: Int) {
        for (i in count - 1 downTo 0) target.append((value ushr i) and 1)
    }

    /** Reads [count] bits of [bits] starting at [offset] as an unsigned integer. */
    private fun bitsToInt(bits: CharSequence, offset: Int, count: Int): Int {
        var value = 0
        for (i in 0 until count) value = (value shl 1) or (bits[offset + i] - '0')
        return value
    }
