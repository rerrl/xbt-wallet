package com.xbtwallet.app.crypto

import com.xbtwallet.app.chain.TxInput
import com.xbtwallet.app.chain.TxOutput
import com.xbtwallet.app.chain.buildUnsignedTransaction
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotEquals
import org.junit.Test

/**
 * The hot-wallet spend the node rejected, reproduced against its **real prevout**
 * and the production digest call.
 *
 * Every value here is the real one, not a synthetic fixture:
 *
 * - the input is `a59947e5…99bc:1`, a 50 000-sat native-P2WPKH output whose
 *   scriptPubKey is `0014 16104dc319a2631232f303a1d97f1fc8609728ea`;
 * - the single output is 49 890 sats to
 *   `00147a5e93aebba24247a69917aec1d0cb7aa573512a` (fee 110, no change);
 * - the transaction is exactly what [buildUnsignedTransaction] builds for a
 *   send — version 2, every sequence final, locktime 0 — which is the shape the
 *   wallet broadcast.
 *
 * The expected digest is the appropriate reference value quoted for this exact
 * transaction (`seq=ffffffff ver=2 lt=0`). It is **not** generated by the code
 * under test, and it is the same number a node running the specification's
 * algorithm computes.
 *
 * **Why this test exists.** `UnifiedSighashTest` reproduces the specification's
 * own 166-row vector file through `unifiedDigestWithScript`, which is handed a
 * `scriptCode` and serialises it itself. That is a different entry point from the
 * one a spend uses: [Sighash.unifiedPreimage] derives the `scriptCode` from the
 * witness utxo. The two can disagree — and they did — with every vector green.
 * This test drives the production entry point on a real spend, so the divergence
 * the vectors cannot see fails here instead of on a node.
 *
 * The recorded txid is pinned too: it is the id of the transaction the node
 * answered about, so it proves this is the same transaction (a txid covers the
 * non-witness serialization, which is what [buildUnsignedTransaction] produces).
 */
class RealPrevoutUnifiedSighashTest {

    private fun hex(text: String): ByteArray =
        ByteArray(text.length / 2) { index ->
            ((text[index * 2].digitToInt(16) shl 4) or text[index * 2 + 1].digitToInt(16)).toByte()
        }

    private fun h(bytes: ByteArray) = bytes.joinToString("") { "%02x".format(it) }

    /** The outpoint being spent, exactly as the chain reports it. */
    private val spentTxid = "a59947e55570b459020d619cee47f8b78caad73b9277bbc42abbfbbaa5e899bc"

    private val spentScript = "001416104dc319a2631232f303a1d97f1fc8609728ea"

    private val recipientScript = "00147a5e93aebba24247a69917aec1d0cb7aa573512a"

    /** `buildUnsignedTransaction`'s shape: version 2, sequence final, locktime 0. */
    private val unsigned: ByteArray get() = buildUnsignedTransaction(
        inputs = listOf(TxInput(spentTxid, 1)),
        outputs = listOf(TxOutput(49_890L, recipientScript)),
    )

    private val tx get() = decodeTransaction(unsigned)

    private val spentOutputs get() = listOf(WitnessUtxo(50_000L, hex(spentScript)))

    /** The reference digest for this transaction under the wallet's own tx shape. */
    private val referenceDigest = "5a472859db77ff95e33cab569e0e1264c70bfaacfcd4e439af54364fafe8d685"

    @Test
    fun `the built transaction is the one the node rejected`() {
        assertEquals(
            "the unsigned transaction must be the broadcast one (its txid is pinned by the node)",
            "ec9119df466f3ff964c9a2a6772669edb3592150e66002949b5cb713d2012a6d",
            transactionId(unsigned),
        )
        assertEquals("version", 2L, tx.version)
        assertEquals("locktime", 0L, tx.lockTime)
        assertEquals("sequence", 0xFFFFFFFFL, tx.inputs[0].sequence)
        assertEquals("inputs", 1, tx.inputs.size)
        assertEquals("outputs", 1, tx.outputs.size)
        assertEquals("output value", 49_890L, tx.outputs[0].satoshis)
        assertEquals("output index", 1L, tx.inputs[0].outputIndex)
    }

    /**
     * The production digest for input 0 — [Sighash.p2wpkhDigest], the exact call
     * [PsbtSigner.signPsbt] makes — must be the reference value.
     */
    @Test
    fun `the production unified digest is the reference digest`() {
        val digest = Sighash.p2wpkhDigest(tx, 0, spentOutputs, SIGHASH_UNIFIED)
        assertEquals(
            "the digest the wallet signs must be the node's message for this spend",
            referenceDigest,
            h(digest),
        )
    }

    /**
     * And it is not the BIP-143 message: the two are different strings, which is
     * why appending `0x21` to a BIP-143 signature could never verify.
     */
    @Test
    fun `the unified digest is not the BIP-143 digest`() {
        val unified = h(Sighash.p2wpkhDigest(tx, 0, spentOutputs, SIGHASH_UNIFIED))
        val legacy = h(Sighash.p2wpkhLegacyDigest(tx, 0, spentOutputs[0]))
        assertNotEquals(unified, legacy)
    }

    /**
     * The field-level statement of the same thing, so a failure names the bug
     * rather than only a number: for a `SIGHASH_ALL` segwit-v0 input the message
     * ends with the `scriptCode`, serialised as **compact-size length, then the
     * script** — `0x19` then the 25-byte implied P2PKH script, 26 bytes in all.
     * A `0x1a 0x19` pair at the tail is the doubled length prefix.
     */
    @Test
    fun `the unified message ends with the scriptCode serialised once`() {
        val preimage = Sighash.unifiedPreimage(tx, 0, spentOutputs, SIGHASH_UNIFIED)
        val p2pkh = "76a914" + spentScript.substring(4) + "88ac"
        assertEquals(
            "the tail must be compact-size(25) then the 25-byte implied P2PKH script",
            "19$p2pkh",
            h(preimage.copyOfRange(preimage.size - 26, preimage.size)),
        )
        assertNotEquals(
            "the tail must not carry a second length byte — 0x1a 0x19 is the doubled prefix",
            "1a19$p2pkh",
            h(preimage.copyOfRange(preimage.size - 27, preimage.size)),
        )
    }
}
